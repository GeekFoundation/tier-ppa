#!/usr/bin/env bash
# Install tierd from the Geek Foundation PPA.
#
# Usage:
#   curl -fsSL https://raw.githubusercontent.com/GeekFoundation/tier-ppa/main/scripts/install.sh | bash
#   curl -fsSL https://raw.githubusercontent.com/GeekFoundation/tier-ppa/main/scripts/install.sh | bash -s -- --unattended-upgrade
#
# Options:
#   --unattended-upgrade   Also configure Ubuntu's unattended-upgrades to keep
#                          tierd updated automatically.
#   --preset=<name>        (future) Select a named node config preset shipped by
#                          the package. Default: the upstream default (client).
#
# Re-running this script is safe: already-completed steps are skipped.

set -euo pipefail

PPA="geekfoundation/tier"
PACKAGE="tierd"
AUTO_UPGRADE=false

# ---------------------------------------------------------------------------
# Parse arguments
# ---------------------------------------------------------------------------
for arg in "$@"; do
    case "$arg" in
        --unattended-upgrade)
            AUTO_UPGRADE=true
            ;;
        --preset=*)
            # Reserved for future use.
            echo "note: --preset is not yet implemented; ignoring" >&2
            ;;
        *)
            echo "error: unknown argument: $arg" >&2
            exit 1
            ;;
    esac
done

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
_ppa_owner="${PPA%%/*}"
_ppa_name="${PPA#*/}"

need_root() {
    if [ "$(id -u)" -ne 0 ]; then
        echo "error: run as root or with sudo" >&2
        exit 1
    fi
}

step() { echo "==> $*"; }
skip() { echo "    (skip) $*"; }

# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------
need_root

if ! grep -qi "ubuntu" /etc/os-release 2>/dev/null; then
    echo "error: this script requires Ubuntu" >&2
    exit 1
fi

# ---------------------------------------------------------------------------
# Step 1: add-apt-repository if the PPA source is not yet present
# ---------------------------------------------------------------------------
ppa_list="/etc/apt/sources.list.d/${_ppa_owner}-ubuntu-${_ppa_name}-*.list"
ppa_sources="/etc/apt/sources.list.d/${_ppa_owner}-ubuntu-${_ppa_name}-*.sources"

if ls $ppa_list $ppa_sources 2>/dev/null | grep -q .; then
    skip "PPA ppa:${PPA} already added"
else
    step "Adding PPA ppa:${PPA}"
    apt-get install -y --no-install-recommends software-properties-common >/dev/null
    add-apt-repository -y "ppa:${PPA}"
    apt-get update -qq
fi

# ---------------------------------------------------------------------------
# Step 2: install the package
# ---------------------------------------------------------------------------
if dpkg-query -W -f='${Status}' "$PACKAGE" 2>/dev/null | grep -q "install ok installed"; then
    skip "$PACKAGE is already installed ($(dpkg-query -W -f='${Version}' "$PACKAGE"))"
else
    step "Installing $PACKAGE"
    apt-get install -y "$PACKAGE"
fi

# ---------------------------------------------------------------------------
# Step 3 (optional): configure unattended-upgrades
# ---------------------------------------------------------------------------
UPGRADE_CONF="/etc/apt/apt.conf.d/51${_ppa_owner}-${_ppa_name}"

if [ "$AUTO_UPGRADE" = true ]; then
    if [ -f "$UPGRADE_CONF" ]; then
        skip "unattended-upgrades already configured ($UPGRADE_CONF)"
    else
        step "Enabling unattended-upgrades for ppa:${PPA}"

        apt-get install -y --no-install-recommends unattended-upgrades >/dev/null

        # Derive the apt Origin label from the InRelease file so we never
        # hardcode it (the label is set by Launchpad and may differ from
        # the PPA slug in edge cases).
        origin=$(grep "^Origin:" \
            /var/lib/apt/lists/ppa.launchpadcontent.net_${_ppa_owner}_${_ppa_name}_ubuntu_dists_*_InRelease \
            2>/dev/null | head -n1 | awk '{print $2}')

        if [ -z "$origin" ]; then
            echo "error: could not determine apt Origin for ppa:${PPA}" >&2
            echo "       run 'apt-get update' and retry" >&2
            exit 1
        fi

        series=$(. /etc/os-release && echo "$VERSION_CODENAME")

        cat > "$UPGRADE_CONF" <<EOF
// Auto-generated by the tierd install script. Remove this file to disable
// automatic updates for tierd.
Unattended-Upgrade::Allowed-Origins {
    "${origin}:${series}";
};
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
EOF
        echo "    configured: $UPGRADE_CONF"
        echo "    origin: ${origin}:${series}"
    fi
fi

# ---------------------------------------------------------------------------
# Done
# ---------------------------------------------------------------------------
echo
echo "tierd $(dpkg-query -W -f='${Version}' "$PACKAGE") is installed."
if [ "$AUTO_UPGRADE" = true ]; then
    echo "Automatic updates: enabled (unattended-upgrades)"
else
    echo "Automatic updates: disabled"
fi
echo
echo "Edit /etc/tier/tierd.toml if needed, then:"
echo "  systemctl start tierd"
